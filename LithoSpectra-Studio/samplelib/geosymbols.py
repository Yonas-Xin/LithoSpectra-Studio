"""地质命名用的符号表与上下标转换。

上下标为什么用 Unicode 字符而不是格式标记
----------------------------------------
类别名要走的地方很多：样本树、检查器、导出的 shp 文件名与属性表、labels.json、
裁剪出来的 h5、光谱图例。存成 ``T<sub>3</sub>`` 或 ``T_3`` 这样的标记，每一处都
得认得它、各自渲染一遍，漏一处就露出一串尖括号。直接存 ``T₃``：它就是一个普通
字符串，所有地方原样显示，文件名、属性表、JSON 都不需要任何特殊处理。

代价是 Unicode 的上下标字符不全：下标只有数字、``+ - = ( )`` 和十几个小写字母，
上标除 ``q`` 以外的小写字母都有、大写字母缺 C F Q S X Y Z。地质上常用的那些
——年代的 ``₁₂₃₄``、范围的 ``₋``、第四系成因的 ``ᵃˡ ᵖˡ ᵈˡ``、离子价态的
``²⁺ ³⁺``——全在里面。转不了的字符原样保留，由调用方告诉使用者。

检索时用 :func:`fold` 把上下标折回普通字符，搜 ``T3`` 能找到 ``T₃``。
"""

from typing import Dict, List, Sequence, Tuple

