def age_symbols() -> List[Tuple[str, List[Symbol]]]:
    """按年代成行的按钮：[(年代名, [(插入文字, 按钮字, 提示), ...]), ...]。"""
    return [(name, [(text, text, "%s  %s" % (tip, text)) for text, tip in row])
            for name, row in AGES]


