#: 上下标字符 -> 普通字符。两张表里同一个普通字符各有一个变体，合起来反查。
_PLAIN: Dict[str, str] = {}
for _table in (SUBSCRIPT, SUPERSCRIPT):
    for _plain, _fancy in _table.items():
        _PLAIN[_fancy] = _plain

#: 中文输入法下打出来的全角括号、加减号，也当成能转的
_WIDE = {"（": "(", "）": ")", "＋": "+", "－": "-", "＝": "=", "—": "-", "–": "-"}

NORMAL, SUB, SUP = "normal", "sub", "sup"


def convert_char(ch: str, mode: str) -> Tuple[str, bool]:
    """把一个字符换成 ``mode`` 下的写法，返回 (结果, 换没换成)。

    已经是上下标的先折回普通字符再换，所以下标可以直接改成上标。
    ``mode`` 为 :data:`NORMAL` 时就是折回普通字符。
    """
    base = _PLAIN.get(ch, _WIDE.get(ch, ch))
    if mode == NORMAL:
        return base, True
    table = SUBSCRIPT if mode == SUB else SUPERSCRIPT
    if base in table:
        return table[base], True
    if base.isspace():
        return base, True
    return ch, False


def convert(text: str, mode: str) -> Tuple[str, str]:
    """整段转换，返回 (结果, 没能转换的字符)。"""
    out: List[str] = []
    missed: List[str] = []
    for ch in text:
        new, ok = convert_char(ch, mode)
        out.append(new)
        if not ok and ch not in missed:
            missed.append(ch)
    return "".join(out), "".join(missed)


def script_of(text: str) -> str:
    """一段文字整体是下标、上标还是普通的。空白不算数；混着的算普通。"""
    kinds = set()
    for ch in text:
        if ch.isspace():
            continue
        if ch in SUBSCRIPT.values():
            kinds.add(SUB)
        elif ch in SUPERSCRIPT.values():
            kinds.add(SUP)
        else:
            kinds.add(NORMAL)
    return kinds.pop() if len(kinds) == 1 else NORMAL


def fold(text: str) -> str:
    """检索用：上下标折回普通字符。``T₃`` -> ``T3``，``Qᵃˡ`` -> ``Qal``。"""
    return "".join(_PLAIN.get(ch, ch) for ch in (text or ""))


def sub(text: str) -> str:
    return convert(text, SUB)[0]


def sup(text: str) -> str:
    return convert(text, SUP)[0]


